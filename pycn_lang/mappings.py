def _build_global_name_map():
    """
    汇总普通名字位置的映射（语言内置层）：
    内置函数 / 内置常量 / 异常 / 魔术名字。
    标准库模块名与库 API 不在此列——它们只在 import 语境与属性位置生效，
    以免把用户自定义的同名标识符（如变量「分数」、函数「阶乘」）误译。
    """
    result = {}
    for table in (
        BUILTIN_FUNCTIONS,
        BUILTIN_CONSTANTS,
        EXCEPTION_MAP,
        DUNDER_MAP,
    ):
        for key, value in table.items():
            if key not in result:
                result[key] = value
    return result


def _build_attribute_map():
    """汇总点号属性位置的映射：类型方法 / 库 API / 魔术名字。"""
    result = {}
    for table in (TYPE_METHODS, LIBRARY_API, DUNDER_MAP):
        for key, value in table.items():
            if key not in result:
                result[key] = value
    return result


GLOBAL_NAME_MAP = _build_global_name_map()
ATTRIBUTE_MAP = _build_attribute_map()
